#!/usr/bin/env python3
"""The one Freeweights license table, loaded from policy/licenses.json.

  licenses.py                 print the table
  licenses.py --write-docs    rewrite the generated blocks in the policy page and the site docs
  licenses.py --check-docs    exit 1 if those blocks are out of date (validate_spec.py runs this)

Every script that decides a license imports this module: build_catalog.py, make_manifest.py,
classify.py. Verdicts: permissive, custom (click-through), non-commercial (link only), refused.
A license id that is held or unknown is not a verdict: it goes to the review queue. Stdlib only."""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE_PATH = os.path.join(ROOT, "policy", "licenses.json")
DOC_PATHS = [os.path.join(ROOT, "policy", "license-allowlist.md"), os.path.join(ROOT, "site", "content", "docs", "licenses.md")]
START, END = "<!-- license-table:start (generated by scripts/licenses.py --write-docs; edit policy/licenses.json) -->", "<!-- license-table:end -->"

with open(TABLE_PATH, encoding="utf-8") as _f: _T = json.load(_f)
VERDICTS = _T["verdicts"]
STRICTNESS = _T["strictness"]          # least to most strict; "queue" sits between non-commercial and refused
LICENSES = {k.lower(): v for k, v in _T["licenses"].items()}
HELD = {k.lower(): v for k, v in _T["held"].items()}
NO_LICENSE = _T["no_license"]
REVIEWED_TEXTS = _T["reviewed_texts"]
PERMISSIVE = frozenset(k for k, v in LICENSES.items() if v["verdict"] == "permissive")

def norm(lid): return str(lid or "").strip().lower()

def entry(lid):
    """Table entry for a license id (any case), or None."""
    return LICENSES.get(norm(lid))

def verdict(lid):
    """Verdict for a license id a person entered or audited (the licenses.csv column).
    Returns permissive | custom | non-commercial | refused | queue."""
    e = entry(lid)
    if e: return e["verdict"]
    if not norm(lid) or norm(lid) in ("none", "unspecified", "unknown"): return NO_LICENSE["verdict"]
    return "queue"

def tag_verdict(tag):
    """Verdict for a publisher-declared Hugging Face license tag with no person reading it.
    Only entries marked tag=true count ("license as declared by the publisher").
    Returns (verdict, reason)."""
    t = norm(tag)
    if not t: return NO_LICENSE["verdict"], NO_LICENSE["note"]
    e = LICENSES.get(t)
    if e and e.get("tag"): return e["verdict"], e.get("note") or f"{e['name']}, as declared by the publisher"
    if t in HELD: return "queue", HELD[t]
    return "queue", f"license tag {t!r} is not in the table"

def text_verdict(sha256):
    """Verdict for a license text a person already read, matched by the sha256 of the text, or None."""
    r = REVIEWED_TEXTS.get(str(sha256 or "").lower())
    return (r["verdict"], r["license_id"]) if r else None

def is_permissive(lid): return verdict(lid) == "permissive"

def redistribution(v):
    """Manifest/catalog redistribution value for a verdict."""
    return VERDICTS[v]["redistribution"] if v in VERDICTS else None

def name(lid):
    """Display name. Ids missing from the table keep their id as the name."""
    e = entry(lid)
    return e["name"] if e else str(lid)

def stricter(a, b):
    """The stricter of two verdicts (strictness order in the table)."""
    return a if STRICTNESS.index(a) >= STRICTNESS.index(b) else b

def strictest(vs):
    out = STRICTNESS[0]
    for v in vs: out = stricter(out, v)
    return out

# ---------- generated docs ----------
def _read(p):
    with open(p, encoding="utf-8") as f: return f.read()

def table_markdown():
    rows = {}
    for k, e in sorted(LICENSES.items(), key=lambda kv: kv[1]["name"].lower()):
        rows.setdefault(e["verdict"], [])
        label = e["name"] if e["name"].lower() == k else f"{e['name']} (`{k}`)"
        if label not in rows[e["verdict"]]: rows[e["verdict"]].append(label + ("" if e.get("tag") else " *"))
    out = ["| Verdict | What happens | Licenses |", "| --- | --- | --- |"]
    for v in ("permissive", "custom", "non-commercial", "refused"):
        out.append(f"| {VERDICTS[v]['label']} | {VERDICTS[v]['meaning']} | {', '.join(rows.get(v, [])) or 'none yet'} |")
    held = {}
    for k, why in HELD.items(): held.setdefault(why, []).append(f"`{k}`")
    lines = ["", "A license marked * was read by a person; the rest list on the publisher's own tag with no person reading it, and the page says \"license as declared by the publisher\".", "",
             "Waiting for a decision, so not listed yet (each goes to the review queue):", ""]
    lines += [f"- {', '.join(ids)}: {why}" for why, ids in held.items()]
    lines += ["- No license declared: refused.", f"- {len(REVIEWED_TEXTS)} license texts a person has read are matched by the sha256 of the text."]
    return "\n".join(out + lines)

def render(doc):
    block = f"{START}\n{table_markdown()}\n{END}"
    if START not in doc or END not in doc: raise ValueError("license-table markers missing")
    return re.sub(re.escape(START) + r"[\s\S]*?" + re.escape(END), lambda _: block, doc)

def docs_status():
    """[(path, ok)] for every doc that embeds the table."""
    out = []
    for p in DOC_PATHS:
        cur = _read(p)
        try: out.append((p, render(cur) == cur))
        except ValueError: out.append((p, False))
    return out

def main(argv):
    if "--write-docs" in argv:
        for p in DOC_PATHS:
            cur = _read(p); new = render(cur)
            if new != cur: open(p, "w", encoding="utf-8", newline="\n").write(new); print("wrote", os.path.relpath(p, ROOT))
        return 0
    if "--check-docs" in argv:
        bad = [p for p, ok in docs_status() if not ok]
        for p in bad: print("out of date:", os.path.relpath(p, ROOT), "(run scripts/licenses.py --write-docs)")
        return 1 if bad else 0
    print(table_markdown()); return 0

if __name__ == "__main__": sys.exit(main(sys.argv[1:]))
