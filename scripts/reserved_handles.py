#!/usr/bin/env python3
"""Generate the reserved-handles seed for the freeweights-accounts database (spec/accounts-v1.md, "Handles").

Reserved: every catalog publisher (the org part of each catalog id), every catalog section id and its short
name, the site's top-level route words, and the product names. Nobody can register these as a user handle
or org slug; the database triggers in worker/migrations-accounts/0001_accounts.sql enforce it.
Stdlib only. Output is sorted and stable, so a re-run on the same catalog gives the same file.

  python3 scripts/reserved_handles.py                 # write worker/migrations-accounts/0002_reserved_handles.sql
  python3 scripts/reserved_handles.py --check         # exit 1 if a catalog handle is in no migrations-accounts/*.sql file
  python3 scripts/reserved_handles.py --only-new --out worker/migrations-accounts/00NN_reserved_handles.sql
        # after a catalog batch: only handles no earlier migrations-accounts/*.sql file reserves
"""
import argparse, glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, "catalog", "catalog.json")
MIG = os.path.join(ROOT, "worker", "migrations-accounts")
SEED = os.path.join(MIG, "0002_reserved_handles.sql")
SECTION_PREFIX = "alt.freeweights."

# Top-level path words the site, the Worker and the planned account pages use (or will use). A handle equal
# to one of these would make /<handle>/<repo> ambiguous with a site page.
ROUTES = sorted({
    "about", "account", "admin", "api", "apps", "assets", "auth", "blog", "catalog", "charter", "collections",
    "data", "datasets", "design", "docs", "endpoints", "enterprise", "ethos", "evals", "explore", "faq",
    "health", "help", "join", "ledger", "login", "logout", "manifests", "mirrors", "models", "new",
    "notifications", "operating-statement", "organizations", "orgs", "papers", "plans", "posts", "pricing",
    "privacy", "search", "security", "settings", "sign-in", "sign-up", "spaces", "static", "status", "studio",
    "team", "terms", "tools", "trending", "users", "wanted", "alt", "alt.freeweights",
})
BRANDS = sorted({"allternit", "freeweights", "gizzi"})
HANDLE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{1,41}$")


def collect():
    cat = json.load(open(CATALOG, encoding="utf-8"))
    out = {}  # lower(handle) -> (handle, reason, source); first reason wins in this order

    def add(handle, reason, source=None):
        if not HANDLE.match(handle) or ".." in handle or "--" in handle:
            # A name the handle rules could never accept needs no reservation; say so instead of dropping it silently.
            print(f"note: {handle!r} ({reason}) cannot be a handle anyway; not reserved", file=sys.stderr)
            return
        out.setdefault(handle.lower(), (handle, reason, source))

    for org in sorted({r["id"].split("/", 1)[0] for r in cat.get("models", [])}, key=str.lower):
        add(org, "catalog_org")
    for s in sorted(cat.get("sections", []), key=lambda s: s["id"]):
        sid = s["id"]
        add(sid, "section")
        if sid.startswith(SECTION_PREFIX):
            add(sid[len(SECTION_PREFIX):], "section", sid)
    for w in ROUTES:
        add(w, "route")
    for b in BRANDS:
        add(b, "brand")
    return [out[k] for k in sorted(out)]


def already_reserved():
    seen = set()
    for p in sorted(glob.glob(os.path.join(MIG, "*.sql"))):
        for m in re.finditer(r"^\s*\('((?:[^']|'')+)',\s*'(?:catalog_org|section|route|brand)'", open(p, encoding="utf-8").read(), re.M):
            seen.add(m.group(1).replace("''", "'").lower())
    return seen


def q(v):
    return "NULL" if v is None else "'" + v.replace("'", "''") + "'"


def render(rows, title):
    lines = [
        f"-- {title}",
        "-- GENERATED by scripts/reserved_handles.py from catalog/catalog.json. Do not edit by hand.",
        f"-- {len(rows)} handles. INSERT OR IGNORE, so the file is safe to run more than once.",
    ]
    for i in range(0, len(rows), 100):  # D1 caps statement size; 100 rows per INSERT stays far under it
        chunk = rows[i:i + 100]
        lines.append("INSERT OR IGNORE INTO reserved_handles (handle, reason, source) VALUES")
        lines.append(",\n".join(f"  ({q(h)}, {q(r)}, {q(s)})" for h, r, s in chunk) + ";")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=SEED)
    ap.add_argument("--check", action="store_true", help="fail if a current handle is reserved by no migration file")
    ap.add_argument("--only-new", action="store_true", help="leave out handles an earlier migration already reserves")
    a = ap.parse_args()
    rows = collect()
    if a.check:
        a.only_new = False
    title = "0002: reserved handles (catalog publishers, section ids, route words, product names)."
    if a.only_new:
        seen = already_reserved()
        rows = [r for r in rows if r[0].lower() not in seen]
        title = os.path.basename(a.out) + ": handles reserved after a catalog update."
        if not rows:
            print("no new handles to reserve"); return 0
    text = render(rows, title)
    if a.check:
        seen = already_reserved()
        missing = [h for h, _, _ in rows if h.lower() not in seen]
        if missing:
            print(f"{len(missing)} handles are not reserved by any migration (first: {', '.join(missing[:5])}): "
                  "run scripts/reserved_handles.py --only-new --out worker/migrations-accounts/00NN_reserved_handles.sql",
                  file=sys.stderr); return 1
        print(f"ok: all {len(rows)} handles are reserved by worker/migrations-accounts/*.sql"); return 0
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(a.out, ROOT)}: {len(rows)} handles")
    return 0


if __name__ == "__main__":
    sys.exit(main())
